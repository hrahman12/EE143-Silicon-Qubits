"""Milestone D, rev B: differential (balanced) launcher lines on the chip.

1. builds the row block with the differential lines (hardware/diffpairs.py sizing, hardware/layout.py drawing),
   writes circuits/qbfx2_layout.gds and circuits/block_ports.json (ports + the path of every P/N leg)
2. DRC (hardware/drc.py) of the new block
3. loop check on the drawn GDS: for every trap/accelerator line, the P and N pins are one Nb piece that touches
   no ground and no other pin (a floating loop: no current can return through the ground)
4. coupling as drawn vs the targets, and cross-talk before/after: the rev-A single-ended lines (their own sizing,
   from git) and the rev-B pairs, same 2D cross-section model (extract.column_inductance)
Writes results/D_diffpairs.json.
"""
import json
import os
import subprocess
import sys
import time

import numpy as np

from _common import ROOT, CIRCUITS, save_json
from hardware.architecture import Architecture
from hardware import layout as LY, drc as D
from hardware import diffpairs as DP

t0 = time.time()
arch = Architecture.from_results(ROOT)
sz = LY.get_sizing(arch)
assert sz.get("line_model") == DP.LINE_MODEL, "sizing is not differential"
res = dict(line_model=sz["line_model"], line_scale=sz["line_scale"], sizing_log=sz.get("log", {}).get("lines"))

# 1. block + ports
gds = os.path.join(CIRCUITS, "qbfx2_layout.gds")
dims = LY.build(arch, gds)
lib, cell, ports, blk = LY.build_block(arch)
legs = {k: [[round(x, 4), round(y, 4)] for x, y in v] for k, v in getattr(blk.geo, "line_paths", {}).items()}
bp = dict(block_gds="circuits/qbfx2_layout.gds", block_cell="QBFX2_ROWS", width_um=blk.W, height_um=blk.H,
          revision="B (differential launcher lines)",
          note="row-block interface for the die floorplan (block coordinates, um); regenerated by "
               "simulations/D_diffpairs.py. Fast lines are P/N pairs: each pair is one floating Nb loop.",
          ports=ports, leg_paths=legs)
json.dump(bp, open(os.path.join(CIRCUITS, "block_ports.json"), "w"), indent=1)
res["block"] = dict(width_um=blk.W, height_um=blk.H, ports=len(ports),
                    pair_ports=sorted(p["name"] for p in ports if p.get("pair")))
print("block:", blk.W, "x", blk.H, "um,", len(ports), "ports;", len(res["block"]["pair_ports"]), "pair pins")

# 2. DRC
r = D.run(gds, arch)
res["drc"] = dict(violations_total=r["violations_total"], summary=r["summary"], junctions=r["junctions"])
print("DRC:", r["violations_total"], {k: v for k, v in r["summary"].items() if v})

# 3. loop check on the GDS
import gdstk
from shapely.geometry import Polygon, Point
from shapely.ops import unary_union
top = [c for c in gdstk.read_gds(gds).top_level() if c.name == "QBFX2_ROWS"][0]
nb = unary_union([Polygon(p.points).buffer(0) for p in top.get_polygons(layer=1, datatype=0)])
comps = list(nb.geoms) if hasattr(nb, "geoms") else [nb]
ext = [p for p in ports if p.get("kind") != "internal_short"]


def comp_of(p):
    pt = Point(p["x"], p["y"])
    hits = [i for i, c in enumerate(comps) if c.distance(pt) < 0.05]
    return hits[0] if hits else None


loops = {}
for p in ports:
    if p.get("polarity") == "P":
        n = next(q for q in ports if q.get("pair") == p["pair"] and q.get("polarity") == "N")
        ci, cn = comp_of(p), comp_of(n)
        others = [q["name"] for q in ext if q["name"] not in (p["name"], n["name"]) and comp_of(q) == ci]
        c = comps[ci] if ci is not None else None
        loops[p["pair"]] = dict(P_and_N_one_piece=bool(ci is not None and ci == cn), other_pins_on_it=others,
                                touches_ground=bool(any("GND" in o for o in others)),
                                area_um2=round(c.area, 2) if c is not None else None,
                                length_um=round(c.area / 0.5, 1) if c is not None else None)
res["loops"] = loops
ok_loops = all(v["P_and_N_one_piece"] and not v["other_pins_on_it"] for v in loops.values())
res["loops_ok"] = ok_loops
print("loops:", "all floating and closed" if ok_loops else loops)

# 4. coupling as drawn + cross-talk before/after (same model)
ad = DP.as_drawn(arch, sz, stride=1)
try:
    revA = json.loads(subprocess.run(["git", "show", "347d5aa:qbf-x2/circuits/layout_sizing.json"], cwd=ROOT,
                                     capture_output=True, text=True, check=True).stdout)
    se = DP.single_ended_reference(arch, revA, rows=("A0", "A1"), stride=1)
except Exception as e:                                       # pragma: no cover
    se = {"error": str(e)}
cmp_ = {}
for row in ("A0", "A1"):
    d = ad[row]["crosstalk"]
    cmp_[row] = dict(rev_A_single_ended=se.get(row), rev_B_differential=d)
    if row in se:
        for k in ("trap", "acc"):
            print(f"{row} {k}: cross-talk into {d[k]['other_rail']} (peak-normalised) "
                  f"rev A {100 * se[row][k]['other_rail_peak_norm']:.1f} % -> rev B {100 * d[k]['other_rail_peak_norm']:.1f} %; "
                  f"at the peak {100 * se[row][k]['other_rail_at_peak']:.1f} % -> {100 * d[k]['other_rail_at_peak']:.1f} %; "
                  f"dummy {100 * se[row][k]['dummy_peak_norm']:.1f} % -> {100 * d[k]['dummy_peak_norm']:.1f} %")
res["crosstalk"] = cmp_
res["as_drawn"] = {row: {k: v for k, v in d.items() if k != "profile"} for row, d in ad.items()}
res["runtime_s"] = time.time() - t0
save_json("D_diffpairs.json", res)
print("done in", round(res["runtime_s"], 1), "s")
